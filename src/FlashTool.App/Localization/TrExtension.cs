using System.Windows.Data;
using System.Windows.Markup;

namespace FlashTool.App.Localization;

/// <summary>
/// <c>Text="{loc:Tr Write_Start}"</c> — binds to a localized string that
/// updates immediately when the language is switched.
/// </summary>
[MarkupExtensionReturnType(typeof(object))]
public sealed class TrExtension : MarkupExtension
{
    public TrExtension()
    {
    }

    public TrExtension(string key) => Key = key;

    [ConstructorArgument("key")]
    public string Key { get; set; } = string.Empty;

    public override object ProvideValue(IServiceProvider serviceProvider)
    {
        var binding = new Binding($"[{Key}]") { Source = Loc.Instance, Mode = BindingMode.OneWay };
        return binding.ProvideValue(serviceProvider);
    }
}
